// run 在后台执行窗口内的操作：成功后刷新 Git 状态并关闭窗口，失败时把错误留在窗口里。
func (f *gitForm) run(name string, op func() error) {
	f.mu.Lock()
	if f.busy {
		f.mu.Unlock()
		return
	}
	f.busy = true
	f.err = ""
	f.mu.Unlock()
	f.invalidate()

	go func() {
		err := op()
		f.mu.Lock()
		f.busy = false
		if err != nil {
			f.err = name + "失败: " + err.Error()
		}
		f.mu.Unlock()
		f.s.loadGitState(f.threadID)
		if err != nil {
			f.invalidate()
			return
		}
		f.close()
	}()
}

// tapSubmitCommit 处理提交按钮点击：AI 还在写提交信息时只记下意图，写完再自动提交；
// 其余情况立即提交。
func (f *gitForm) tapSubmitCommit(generating bool) {
	if generating {
		f.mu.Lock()
		f.commitWhenGenerated = true
		f.mu.Unlock()
		f.invalidate()
		return
	}
	f.submitCommit()
}

// submitCommit 提交当前会话工作目录的改动：全部勾选时沿用一次性提交全部改动的老路径，
// 只勾选部分文件时只提交这些路径；勾选了推送时在提交成功后再推送。
func (f *gitForm) submitCommit() {
	f.mu.Lock()
	msg := strings.TrimSpace(f.commitMsg)
	pushAfter := f.pushAfter
	threadID := f.threadID
	files := append([]GitChangedFile(nil), f.changedFiles...)
	selected := make(map[string]bool, len(f.fileSelected))
	for path, checked := range f.fileSelected {
		selected[path] = checked
	}
	f.mu.Unlock()
	if msg == "" {
		return
	}
	paths, all := gitCommitPaths(files, selected)
	if !all && len(paths) == 0 {
		f.setErr("没有勾选要提交的文件")
		return
	}
	client := f.s.client
	f.run("提交", func() error {
		var err error
		if all {
			err = client.GitCommit(context.Background(), threadID, msg)
		} else {
			err = client.GitCommitSelected(context.Background(), threadID, paths, msg)
		}
		if err != nil {
			return err
		}
		if pushAfter {
			return client.GitPush(context.Background(), threadID)
		}
		return nil
	})
}

// submitNewBranch 创建并切换到窗口里填写的分支。
func (f *gitForm) submitNewBranch() {
	name := strings.TrimSpace(f.branchName)
	if name == "" {
		return
	}
	threadID := f.threadID
	client := f.s.client
	f.run("新建分支", func() error {
		return client.GitCreateBranch(context.Background(), threadID, name)
	})
}

// checkout 切换到列表里选中的分支。
func (f *gitForm) checkout(branch string) {
	if branch == "" {
		return
	}
	threadID := f.threadID
	client := f.s.client
	f.run("切换分支", func() error {
		return client.GitCheckout(context.Background(), threadID, branch)
	})
}

// submitMerge 按窗口里选的方向合并：快进模式把当前分支快进到所选分支，否则把所选分支合并进当前分支。
func (f *gitForm) submitMerge() {
	branch := strings.TrimSpace(f.mergeBranch)
	if branch == "" {
		return
	}
	fastForward := f.mergeFastForward
	threadID := f.threadID
	client := f.s.client
	if fastForward {
		f.run("快进合并", func() error {
			if err := client.GitFastForwardInto(context.Background(), threadID, branch); err != nil {
				return err
			}
			f.s.setToast("已快进合并到 " + branch)
			return nil
		})
		return
	}
	f.run("合并", func() error {
		if err := client.GitMergeFrom(context.Background(), threadID, branch); err != nil {
			return err
		}
		f.s.setToast("已合并 " + branch)
		return nil
	})
}

// loadChangedFiles 在后台读取工作区的改动文件列表，供提交窗口列出来并默认全选。
// 只对提交窗口生效；读取失败时保留空列表，不弹错误。
func (f *gitForm) loadChangedFiles() {
	if f.kind != gitFormCommit {
		return
	}
	threadID := f.threadID
	client := f.s.client

	go func() {
		// 先等 Git 状态就绪，再取工作目录：刚打开窗口时状态可能还没同步回来，
		// 此时把空列表当成「没有改动」并结束读取态，窗口就会误报。
		f.waitGitState()
		if f.s.headerProjectDir(threadID) == "" {
			// 状态确认拿不到工作目录（不是 Git 仓库或加载失败）：结束读取态，回到常规空态。
			f.mu.Lock()
			f.filesLoaded = true
			f.mu.Unlock()
			f.invalidate()
			return
		}

		files, err := client.GitChangedFiles(context.Background(), threadID)
		if err != nil {
			files = nil
		}
		// 打开窗口时默认全部勾选，直接提交等同于原来的「提交全部改动」。
		selected := make(map[string]bool, len(files))
		for _, file := range files {
			selected[file.Path] = true
		}
		f.mu.Lock()
		f.changedFiles = files
		f.fileSelected = selected
		f.filesLoaded = true
		f.mu.Unlock()
		f.invalidate()
	}()
}

// gitChangedFileLabel 返回改动行的文字：状态字符加路径，重命名同时显示新旧路径。
func gitChangedFileLabel(file GitChangedFile) string {
	label := file.Path
	if file.OrigPath != "" {
		label = file.OrigPath + " -> " + file.Path
	}
	if file.Status != "" {
		label = file.Status + "  " + label
	}
	return label
}

// gitSelectedFileCount 返回勾选的改动文件数量。
func gitSelectedFileCount(files []GitChangedFile, selected map[string]bool) int {
	count := 0
	for _, file := range files {
		if selected[file.Path] {
			count++
		}
	}
	return count
}

// gitCommitPaths 返回要提交的路径与是否等同全选：重命名同时带上新旧路径，保持原顺序且去重。
// 列表为空（还没读出来或读取失败）时返回 all=true，调用方沿用提交全部改动的老路径。
func gitCommitPaths(files []GitChangedFile, selected map[string]bool) (paths []string, all bool) {
	if len(files) == 0 {
		return nil, true
	}
	paths = make([]string, 0, len(files))
	seen := make(map[string]struct{}, len(files))
	for _, file := range files {
		if !selected[file.Path] {
			continue
		}
		// 重命名要同时暂存新旧路径，否则旧路径的删除不会进入这次提交。
		for _, path := range []string{file.OrigPath, file.Path} {
			if strings.TrimSpace(path) == "" {
				continue
			}
			if _, ok := seen[path]; ok {
				continue
			}
			seen[path] = struct{}{}
			paths = append(paths, path)
		}
	}
	return paths, gitSelectedFileCount(files, selected) == len(files)
}

// autoGenerateOnOpen 在提交窗口打开时自动写一次提交信息；已经写过或用户已有草稿时跳过。
func (f *gitForm) autoGenerateOnOpen() {
	if f.kind != gitFormCommit || !isGenerateCommitMessageEnabled(f.s) {
		return
	}
	f.mu.Lock()
	if f.autoGenerated || strings.TrimSpace(f.commitMsg) != "" {
		f.mu.Unlock()
		return
	}
	f.autoGenerated = true
	f.mu.Unlock()

	go func() {
		// 打开瞬间的 Changes 可能只是状态尚未加载时的 0，先等 Git 状态就绪再判断，
		// 否则会静默跳过自动生成。
		if f.waitGitState().Changes == 0 {
			return
		}
		f.generateCommitMessage()
	}()
}

// cancelGeneration 取消正在运行的 AI 生成并复位生成态（调用方需已释放 f.mu）。
func (f *gitForm) cancelGeneration() {
	f.mu.Lock()
	if f.genCancel != nil {
		f.genCancel()
		f.genCancel = nil
	}
	f.genSeq++
	f.generating = false
	f.busy = false
	f.mu.Unlock()
}

// generateCommitMessage 生成提交信息并填进输入框，窗口保持打开。
// 重复点击时会先取消上一次请求。
func (f *gitForm) generateCommitMessage() {
	f.mu.Lock()
	// 重复点击生成：先取消正在跑的旧请求，旧结果不会再覆盖新结果。
	if f.genCancel != nil {
		f.genCancel()
	}
	ctx, cancel := context.WithCancel(context.Background())
	f.genCancel = cancel
	f.genSeq++
	seq := f.genSeq
	f.busy = true
	f.generating = true
	f.err = ""
	f.mu.Unlock()
	f.invalidate()

	threadID := f.threadID
	client := f.s.client
	go func() {
		out, err := client.GenerateCommitMessage(ctx, threadID)
		f.mu.Lock()
		if seq != f.genSeq {
			// 已被新请求或窗口关闭取消：丢弃这次结果。
			f.mu.Unlock()
			return
		}
		f.genCancel = nil
		f.busy = false
		f.generating = false
		if err != nil {
			f.err = "AI 生成失败: " + err.Error()
			// 生成失败就没有可提交的信息，清掉「生成后自动提交」的意图。
			f.commitWhenGenerated = false
		} else {
			f.pendingMsg = out
		}
		f.mu.Unlock()
		f.invalidate()
	}()
}

// GitPullRequestCreateURL 按桌面端「创建合并请求」的规则，把远端地址与分支名拼成
// 创建 PR/MR 的网页地址；remoteURL 可以是 ssh / https / SCP 等任意 git remote 形式。
// 供远程协议（git.pr.createUrl）复用，避免另一处再实现一套规则；
// 地址为空或识别不到托管平台时返回空串。
func GitPullRequestCreateURL(remoteURL, branch string) string {
	return gitPullRequestFormURL(normalizeGitRemoteURL(remoteURL), branch, "", "")
}

// gitPullRequestFormURL 在创建合并请求的地址上追加标题与正文，让浏览器预填两者的表单。
func gitPullRequestFormURL(repoURL, branch, title, body string) string {
	base := gitPullRequestURL(repoURL, branch)
	if base == "" {
		return ""
	}
	title = strings.TrimSpace(title)
	body = strings.TrimSpace(body)
	if title == "" && body == "" {
		return base
	}

	values := url.Values{}
	if strings.Contains(strings.ToLower(repoURL), "gitlab") {
		if title != "" {
			values.Set("merge_request[title]", title)
		}
		if body != "" {
			values.Set("merge_request[description]", body)
		}
	} else {
		if title != "" {
			values.Set("title", title)
		}
		if body != "" {
			values.Set("body", body)
		}
	}

	sep := "?"
	if strings.Contains(base, "?") {
		sep = "&"
	}
	return base + sep + values.Encode()
}
