// Git 操作独立窗口的尺寸：提交与切换分支的窗口更高，创建合并请求与新建分支是窄表单。
const (
	gitFormCommitWidth     = 560
	gitFormCommitHeight    = 440
	gitFormNewBranchWidth  = 480
	gitFormNewBranchHeight = 260
	gitFormBranchWidth     = 420
	gitFormBranchHeight    = 520
	gitFormPRWidth         = 480
	gitFormPRHeight        = 400
)

// gitFormStateWaitTimeout 是等待会话 Git 状态就绪的上限：首次打开窗口时头部状态往往还在后台加载，
// WorkDir 与 Changes 都是空值占位，直接拿它们判断会误报「没有改动」。
const gitFormStateWaitTimeout = 2 * time.Second

// Git 操作窗口顶部的垂直留白，按窗口类型区分（见 view 里的 topPad）：
//   - 带标题行的窗口顶部留 44pt 给 macOS 交通灯，再加 13pt 文字行高约 16pt 与 6pt 下内边距，
//     标题行高度约 66pt；
//   - 提交窗口没有标题行，顶部 44pt 留白本身就是让给交通灯的区域。
//
// Windows 上系统按钮要填满 TitleBarHeight，取这两段高度，按钮才不会盖住标题行文字或正文。
const (
	gitFormHeaderHeight         = 66
	gitFormCommitTitleBarHeight = 44
)

// gitFormTitleBarHeight 返回窗口选项 TitleBarHeight 的取值：提交窗口没有标题行，
// 取顶部留白高度；其它窗口取标题行高度。
func gitFormTitleBarHeight(kind gitFormKind) int {
	if kind == gitFormCommit {
		return gitFormCommitTitleBarHeight
	}
	return gitFormHeaderHeight
}

// Git 操作窗口正文的排版尺寸：留白、标题宽度与提交窗口两块区域的高度上限。
const (
	// gitFormTrafficLightPad 是顶部让给 macOS 交通灯与 Windows 系统按钮的留白。
	gitFormTrafficLightPad float32 = 44
	// gitFormBranchNameMaxWidth 是标题行里分支名的最大宽度。
	gitFormBranchNameMaxWidth float32 = 220
	// gitFormCommitBlockMaxHeight 是提交窗口里改动文件卡片与输入框各自的高度上限。
	gitFormCommitBlockMaxHeight float32 = 260
	// gitFormAICapsuleSpinner 是「AI 帮我写」胶囊里菊花的大小。
	gitFormAICapsuleSpinner float32 = 11
	// gitFormBranchScrollFloor / gitFormBranchScrollReserve 是分支列表滚动区的
	// 最小高度与留给窗口头部与按钮的高度。
	gitFormBranchScrollFloor   float32 = 140
	gitFormBranchScrollReserve float32 = 200
	// gitFormMergeScrollFloor / gitFormMergeScrollReserve 是合并请求列表滚动区的最小高度与保留高度。
	gitFormMergeScrollFloor   float32 = 120
	gitFormMergeScrollReserve float32 = 300
)

// gitFormKind 标识在独立窗口里完成的 Git 操作。
type gitFormKind string

const (
	gitFormCommit      gitFormKind = "commit"
	gitFormNewBranch   gitFormKind = "new-branch"
	gitFormCheckout    gitFormKind = "checkout"
	gitFormPullRequest gitFormKind = "pull-request"
	gitFormMerge       gitFormKind = "merge"
)

// gitForm 是一个 Git 操作窗口的状态，按「threadID + 操作类型」注册，重复发起时聚焦已打开的窗口。
// 输入框、按钮只在 UI 线程读写（commitMsg 等字段只在该线程内变更）；
// 后台操作通过 mu 更新 busy、err、pendingMsg 并请求重绘，成功后刷新 Git 状态并关闭窗口。
type gitForm struct {
	mu sync.Mutex

	win        *mygo.Window
	services   ui.Services
	busy       bool
	err        string
	pendingMsg string // AI 生成的提交信息，下一帧填进输入框

	// generating 表示 AI 正在撰写提交信息，用于禁用按钮与切换占位文字；
	// autoGenerated 保证打开窗口后只自动生成一次；
	// commitWhenGenerated 记录用户在生成期间就点了提交，信息回填后自动提交；
	// changedFiles 是工作区改动文件列表，fileSelected 按 Path 记录每一行的勾选状态（默认全选）。
	generating          bool
	autoGenerated       bool
	commitWhenGenerated bool
	changedFiles        []GitChangedFile
	fileSelected        map[string]bool
	filesLoaded         bool

	// genCancel 取消仍在跑的 AI 生成；genSeq 是生成请求序号，
	// 只有序号仍未变化的那次结果才会被写回输入框，
	// 避免旧请求晚到后覆盖新生成的结果。
	genCancel context.CancelFunc
	genSeq    int

	s        *chatState
	threadID string
	kind     gitFormKind

	commitMsg  string
	pushAfter  bool
	branchName string
	query      string
	prTitle    string
	prBody     string

	// mergeFastForward 为 true 表示「快进合并到所选分支」，false 表示「合并到当前分支」；
	// mergeBranch 是在窗口里选中的分支（选中不立即执行，还要点主按钮）。
	// 与 query 一样只在 UI 线程读写，分支搜索复用 query。
	mergeFastForward bool
	mergeBranch      string
}

// gitFormKey 是窗口注册表的键：同一个会话的同一种操作只保留一个窗口。
type gitFormKey struct {
	threadID string
	kind     gitFormKind
}

var (
	gitFormMu      sync.Mutex
	gitFormWindows = make(map[gitFormKey]*gitForm)
	// gitFormWindowHook 创建并显示窗口；测试中替换成不真正开窗的记录桩。
	gitFormWindowHook = showGitFormWindow
)

// waitGitState 在后台等待会话的 Git 状态就绪（最多 gitFormStateWaitTimeout），返回当时的状态。
// 刚打开窗口时头部的 Git 状态可能还在加载，此时 WorkDir 为空、Changes 为 0 都只是占位值；
// 状态还没加载时主动刷新一次，避免窗口一直等不到数据。
func (f *gitForm) waitGitState() GitState {
	if st := f.s.headerGitState(f.threadID); st.WorkDir != "" {
		return st
	}
	f.s.loadGitState(f.threadID)
	deadline := time.Now().Add(gitFormStateWaitTimeout)
	for {
		st := f.s.headerGitState(f.threadID)
		if st.WorkDir != "" || !time.Now().Before(deadline) {
			return st
		}
		time.Sleep(50 * time.Millisecond)
	}
}

// openGitForm 打开指定会话的 Git 操作窗口；该操作已经有窗口时聚焦它并直接返回。
func openGitForm(s *chatState, threadID string, kind gitFormKind) *gitForm {
	if s == nil || s.client == nil || threadID == "" {
		return nil
	}
	key := gitFormKey{threadID: threadID, kind: kind}
	gitFormMu.Lock()
	if existing, ok := gitFormWindows[key]; ok {
		gitFormMu.Unlock()
		existing.focus()
		return existing
	}
	f := &gitForm{s: s, threadID: threadID, kind: kind}
	gitFormWindows[key] = f
	gitFormMu.Unlock()

	// 提交窗口要列出改了哪些文件，列表在后台读取，读完再重绘。
	f.loadChangedFiles()
	gitFormWindowHook(f)
	return f
}

// focus 把已打开的窗口提到前台。
func (f *gitForm) focus() {
	f.mu.Lock()
	win := f.win
	f.mu.Unlock()
	if win != nil {
		win.Show()
		win.Focus()
	}
}

// close 关闭窗口；窗口还没建起来时直接从注册表移除。
func (f *gitForm) close() {
	f.mu.Lock()
	win := f.win
	f.mu.Unlock()
	if win != nil {
		win.Close()
		return
	}
	f.unregister()
}

// unregister 把窗口从注册表移除，下次点击重新创建。
func (f *gitForm) unregister() {
	// 窗口已经关掉，不会有人接收结果：先把仍在跑的 AI 生成停掉。
	f.cancelGeneration()
	f.dropStashDialogState()
	gitFormMu.Lock()
	key := gitFormKey{threadID: f.threadID, kind: f.kind}
	if gitFormWindows[key] == f {
		delete(gitFormWindows, key)
	}
	gitFormMu.Unlock()
}

// invalidate 请求窗口重绘。
func (f *gitForm) invalidate() {
	f.mu.Lock()
	services := f.services
	f.mu.Unlock()
	if services != (ui.Services{}) {
		services.Invalidate()
	}
}

// setErr 在窗口内显示错误。
func (f *gitForm) setErr(msg string) {
	f.mu.Lock()
	f.err = msg
	f.mu.Unlock()
	f.invalidate()
}

// gitFormTitle 返回操作对应的窗口与标题栏文字。
func gitFormTitle(kind gitFormKind) string {
	switch kind {
	case gitFormCommit:
		return "提交改动"
	case gitFormNewBranch:
		return "新建分支"
	case gitFormCheckout:
		return "切换分支"
	case gitFormPullRequest:
		return "创建合并请求"
	case gitFormMerge:
		return "合并分支"
	default:
		return "Git 操作"
	}
}

// windowSize 返回窗口的初始尺寸。
func (f *gitForm) windowSize() (int, int) {
	switch f.kind {
	case gitFormNewBranch:
		return gitFormNewBranchWidth, gitFormNewBranchHeight
	case gitFormCheckout, gitFormMerge:
		return gitFormBranchWidth, gitFormBranchHeight
	case gitFormPullRequest:
		return gitFormPRWidth, gitFormPRHeight
	default:
		return gitFormCommitWidth, gitFormCommitHeight
	}
}

// stateKey 按「threadID + 操作类型」区分窗口位置记忆。
func (f *gitForm) stateKey() string {
	return "git-form-" + string(f.kind) + "-" + f.threadID
}

// showGitFormWindow 创建并显示 Git 操作窗口，关闭时把窗口从注册表移除。
func showGitFormWindow(f *gitForm) {
	var win *mygo.Window
	width, height := f.windowSize()

	mygo.RunOnMain(func() {
		win = mygo.NewWindow(mygo.WindowOptions{
			Title:                gitFormTitle(f.kind),
			Width:                width,
			Height:               height,
			MinWidth:             width - 80,
			MinHeight:            height - 80,
			TitleBarStyle:        mygo.TitleBarHiddenInset,
			TrafficLightPosition: &mygo.Point{X: 18, Y: 16},
			// Windows 上系统按钮填满 TitleBarHeight：带标题行的窗口取标题行高度，
			// 提交窗口没有标题行，取顶部 44pt 留白的高度。
			TitleBarHeight: hiddenTitleBarHeight(titleBarGOOS, gitFormTitleBarHeight(f.kind)),
			StateKey:       f.stateKey(),
			Content:        ui.View(f.view),
		})
		f.mu.Lock()
		f.win = win
		f.mu.Unlock()
		win.OnClosed(func() {
			f.mu.Lock()
			f.win = nil
			f.mu.Unlock()
			f.unregister()
		})
	})

	// 打开提交窗口时就写一条提交信息；重复聚焦已打开的窗口不会再触发。
	f.autoGenerateOnOpen()
}

// view 构建窗口界面：标题行显示操作名与当前分支，正文按操作类型渲染表单与按钮。
// 提交窗口自己带大标题，不再显示标题行、分支名与「已更改 N 个文件」。
func (f *gitForm) view(c *ui.Context) {
	applyAppTheme(c)
	f.mu.Lock()
	if f.services == (ui.Services{}) {
		f.services = c.Services()
	}
	// AI 生成的结果在后台写入，这里搬到 UI 线程的输入框状态上；
	// 用户已经开始输入时保留自己的草稿。
	autoCommit := false
	if f.pendingMsg != "" {
		if strings.TrimSpace(f.commitMsg) == "" {
			f.commitMsg = f.pendingMsg
		}
		f.pendingMsg = ""
		// 用户在生成期间已经点过提交：信息一到位就接着提交，标记只消费一次。
		if f.commitWhenGenerated && strings.TrimSpace(f.commitMsg) != "" {
			f.commitWhenGenerated = false
			autoCommit = true
		}
	}
	busy := f.busy
	generating := f.generating
	queuedCommit := f.commitWhenGenerated
	errMsg := f.err
	f.mu.Unlock()

	if autoCommit {
		f.submitCommit()
	}

	st := f.s.headerGitState(f.threadID)
	_, height := c.Size()

	// 提交窗口没有标题行，顶部留出交通灯的位置；其它窗口由标题行推出这段间距。
	isCommit := f.kind == gitFormCommit
	topPad, sidePad, bottomPad, bodyGap := float32(0), Space5, Space4, Space3
	if isCommit {
		topPad, sidePad, bottomPad, bodyGap = gitFormTrafficLightPad, Space6, Space5, Space4
	}

	ui.Column(c.Key("git-form-root")).
		Fill().
		Background(ThemeWindowBg(c)).
		Children(func() {
			if !isCommit {
				// 右侧留出 Windows 右上角系统按钮的位置，分支名不会被盖住。
				trailingPad := Space5 + titleBarTrailingInset(c)
				ui.Row(c.Key("git-form-header")).
					FillWidth().
					Padding(gitFormTrafficLightPad, trailingPad, Space2, Space5).
					AlignItems(ui.Center).
					Gap(Space3).
					Children(func() {
						ui.Text(c, gitFormTitle(f.kind)).
							FontSize(TypeBody).
							FontWeight(600).
							TextColor(ThemePrimaryText(c)).
							SingleLine()
						ui.Spacer(c)
						if label := strings.TrimSpace(gitBranchLabel(st)); label != "" {
							ui.Text(c, label).
								FontSize(TypeCaption).
								TextColor(ThemeSecondaryText(c)).
								MaxWidth(gitFormBranchNameMaxWidth).
								SingleLine()
						}
					})
			}

			ui.Column(c.Key("git-form-body")).
				FillWidth().
				Grow(1).
				Padding(topPad, sidePad, bottomPad, sidePad).
				Gap(bodyGap).
				Children(func() {
					switch f.kind {
					case gitFormNewBranch:
						f.viewNewBranch(c, busy, errMsg)
					case gitFormCheckout:
						f.viewCheckout(c, st, busy, errMsg, height)
					case gitFormPullRequest:
						f.viewPullRequest(c, st, busy, errMsg)
					case gitFormMerge:
						f.viewMerge(c, st, busy, errMsg, height)
					default:
						f.viewCommit(c, st, busy, generating, queuedCommit, errMsg)
					}
				})

			// 贮藏列表弹窗叠在窗口内容之上，关闭时自己从渲染树里消失。
			renderGitStashDialog(c, f)
		})
}

// viewCommit 渲染提交窗口，自上而下是：标题、改动文件清单、提交信息输入框、底部操作行。
func (f *gitForm) viewCommit(c *ui.Context, st GitState, busy, generating, queuedCommit bool, errMsg string) {
	f.mu.Lock()
	files := append([]GitChangedFile(nil), f.changedFiles...)
	selected := make(map[string]bool, len(f.fileSelected))
	for path, checked := range f.fileSelected {
		selected[path] = checked
	}
	filesLoaded := f.filesLoaded
	f.mu.Unlock()
	commitMsg := f.commitMsg
	// 全部勾选时沿用一次性提交全部改动的老路径，只有部分勾选才按路径提交。
	commitPaths, commitAll := gitCommitPaths(files, selected)
	selectedCount := gitSelectedFileCount(files, selected)

	ui.Text(c, "提交变更").
		FontSize(TypePageTitle).
		FontWeight(600).
		TextColor(ThemePrimaryText(c))

	if errMsg != "" {
		renderGitError(c, "git-form-commit-error", errMsg)
	}

	// 改动文件卡片：首行是全选开关与已选计数，下面是可滚动的勾选列表。
	// 与输入框平分剩余高度，两者都封顶 260，窗口缩小时不会把按钮挤出去。
	ui.Column(c.Key("git-form-commit-files")).
		FillWidth().
		Grow(1).
		MaxHeight(gitFormCommitBlockMaxHeight).
		Padding(Space3, Space4).
		Radius(RadiusLG).
		Background(ThemeSurface(c)).
		Children(func() {
			// 只有读到文件列表时才显示全选行：列表为空说明还没读完或没有改动。
			if len(files) > 0 {
				ui.Row(c.Key("git-form-commit-files-head")).
					FillWidth().
					Gap(Space3).
					AlignItems(ui.Center).
					Children(func() {
						allChecked := commitAll
						cb := ui.Checkbox(c.Key("git-form-commit-select-all"), &allChecked, "全选")
						if cb.Changed() {
							f.setAllFilesSelected(files, allChecked)
							for _, file := range files {
								selected[file.Path] = allChecked
							}
							commitPaths, commitAll = gitCommitPaths(files, selected)
							selectedCount = gitSelectedFileCount(files, selected)
						}
						ui.Spacer(c)
						ui.Text(c, fmt.Sprintf("已选 %d/%d", selectedCount, len(files))).
							FontSize(TypeCaption).
							TextColor(ThemeSecondaryText(c)).
							SingleLine()
					})
			}
			ui.Scroll(c.Key("git-form-commit-files-scroll")).
				FillWidth().
				Grow(1).
				Children(func() {
					ui.Column(c.Key("git-form-commit-files-list")).
						FillWidth().
						Gap(Space0).
						Children(func() {
							switch {
							// GitState 已经报了改动、但列表还没读出来时，说明状态仍在同步，不能报「没有改动」。
							case len(files) == 0 && (!filesLoaded || st.Changes > 0):
								ui.Text(c, "正在读取改动文件…").
									FontSize(TypeFootnote).
									TextColor(ThemeSecondaryText(c))
							case len(files) == 0:
								ui.Text(c, "工作区里没有未提交的改动").
									FontSize(TypeFootnote).
									TextColor(ThemeSecondaryText(c))
							default:
								for _, file := range files {
									f.renderCommitFileRow(c, file, selected[file.Path])
								}
							}
						})
				})
		})

	// 提交信息输入框：生成中把占位文字换成「正在撰写提交信息…」。
	placeholder := "提交信息"
	if generating {
		placeholder = "正在撰写提交信息…"
	}
	area := ui.TextArea(c.Key("git-form-commit-input"), &commitMsg).
		Label("提交信息").
		Placeholder(placeholder).
		FontSize(TypeBody).
		TextColor(ThemePrimaryText(c)).
		Background(ThemeSurface(c)).
		Border(Hairline, ThemeBorder(c)).
		Radius(RadiusLG).
		Padding(Space3, Space4).
		FillWidth().
		Grow(1).
		MaxHeight(gitFormCommitBlockMaxHeight).
		AutoFocus()
	area.OnChange(func() { f.commitMsg = commitMsg })
	if area.Changed() {
		f.commitMsg = commitMsg
	}
	area.OnTextKey(func(k ui.TextKey) bool {
		if k.Key == ui.KeyEscape {
			f.close()
			return true
		}
		return false
	})

	// 生成中提交按钮不彻底禁用：点下只是记下意图，等 AI 写完信息再自动提交。
	// 一个文件都没勾选（部分勾选且选空）时同样禁用。
	submitText := "提交"
	// submitLabel 是按钮的无障碍名称，为空时按钮默认用 Text；
	// 排队时按钮文字缩短，但仍让屏幕阅读器读到完整含义。
	submitLabel := ""
	submitDisabled := busy || strings.TrimSpace(commitMsg) == "" || st.Changes == 0 || (!commitAll && len(commitPaths) == 0)
	if generating {
		submitDisabled = queuedCommit
		if queuedCommit {
			submitText = "等待提交…"
			submitLabel = "生成完成后自动提交"
		}
	}

	// 底部一行：左边 AI 帮我写与提交后推送，右边取消与提交。
	ui.Row(c.Key("git-form-commit-actions")).
		FillWidth().
		Gap(Space3).
		AlignItems(ui.Center).
		Children(func() {
			// 生成中也允许再点一次：会先取消上一次请求再重新生成；
			// 其它操作（提交、推送）占用时仍禁用。
			f.commitAIAction(c, (busy && !generating) || st.Changes == 0 || !isGenerateCommitMessageEnabled(f.s), generating)
			ui.Checkbox(c.Key("git-form-commit-push-check"), &f.pushAfter, "提交后推送到远程仓库")
			Button(c, ButtonOpts{
				Key:     "git-form-stash-list",
				Text:    "贮藏列表…",
				Variant: ButtonSecondary,
				OnClick: f.openStashDialog,
			})
			ui.Spacer(c)
			Button(c, ButtonOpts{
				Key:     "git-form-cancel",
				Text:    "取消",
				Variant: ButtonSecondary,
				OnClick: f.close,
			})
			if queuedCommit {
				// 已排队等 AI 写完提交信息再自动提交：菊花表示仍在等待，按钮文字显示「等待提交…」。
				ui.Spinner(c).Size(IconSM, IconSM).TextColor(ThemeAccent(c))
			}
			Button(c, ButtonOpts{
				Key:      "git-form-commit-submit",
				Text:     submitText,
				Label:    submitLabel,
				Variant:  ButtonPrimary,
				Disabled: submitDisabled,
				OnClick: func() {
					f.tapSubmitCommit(generating)
				},
			})
		})
}

// renderCommitFileRow 渲染一行可勾选的改动文件：勾选框后跟状态字符与路径。
// 重命名会同时显示新旧路径，方便认出是哪个文件被改了名字。
func (f *gitForm) renderCommitFileRow(c *ui.Context, file GitChangedFile, checked bool) {
	cb := ui.Checkbox(c.Key("git-form-commit-file-"+file.Path), &checked, gitChangedFileLabel(file))
	if cb.Changed() {
		f.setFileSelected(file.Path, checked)
	}
}

