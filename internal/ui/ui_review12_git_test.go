func TestUIReview12ConflictMenuClosesOnBulkResolve(t *testing.T) {
	_, ps, f, tt := newGitDiffTester(t, git.FileDiff{}, "<<<<<<< ours\nA\n=======\nB\n>>>>>>> theirs\n")
	conflicts := []git.ConflictFile{{Path: "a.go"}, {Path: "b.go"}}
	f.gitPaneFakeClient.paneMu.Lock()
	f.gitPaneFakeClient.op = git.OpState{Conflicts: conflicts}
	f.gitPaneFakeClient.paneMu.Unlock()
	ps.mu.Lock()
	ps.op.Conflicts = conflicts
	ps.mu.Unlock()
	tt.Frame()

	for _, tc := range []struct {
		label   string
		confirm string
	}{
		{label: "整个文件用 当前", confirm: "覆盖文件"},
		{label: "全部用 当前", confirm: "全部覆盖"},
	} {
		if err := tt.Click("差异菜单"); err != nil {
			t.Fatal(err)
		}
		tt.Frame()
		st := gitDiffStateFor(ps)
		if !st.menuOpen {
			t.Fatalf("%s 前菜单未打开", tc.label)
		}
		if err := tt.Click(tc.label); err != nil {
			t.Fatal(err)
		}
		tt.Frame()
		if st.menuOpen {
			t.Fatalf("点击 %s 后菜单应关闭", tc.label)
		}
		if !tt.HasText(tc.confirm) {
			t.Fatalf("点击 %s 后未弹出确认弹窗：%v", tc.label, tt.Texts())
		}
		if err := tt.Click(tc.confirm); err != nil {
			t.Fatal(err)
		}
		tt.Frame()
		waitFor(t, tt, func() bool {
			st.mu.Lock()
			defer st.mu.Unlock()
			return !st.pending && !st.loading
		})
	}
	f.diffMu.Lock()
	defer f.diffMu.Unlock()
	if !slices.Contains(f.diffCalls, "ours") {
		t.Fatalf("未触发按侧解决：%v", f.diffCalls)
	}
}

func TestUIReview12CommitBlockedWhileSyncing(t *testing.T) {
	s, ps, base := gitPaneTestState(t)
	s.client = &gitChangesFakeClient{gitPaneFakeClient: base}
	root := t.TempDir()
	ps.mu.Lock()
	ps.state = GitState{WorkDir: root}
	ps.entries = []git.StatusEntry{{Path: "a.txt", Worktree: 'M'}}
	ps.syncing = true
	ps.mu.Unlock()
	st := gitChangesStateFor(ps)
	st.mu.Lock()
	st.root = root
	st.draft = "fix: block during sync"
	st.autoGenerated = true
	st.mu.Unlock()

	tt := ui.NewTester(func(c *ui.Context) { renderGitComposerForTest(c, s, ps) }, 800, 600)
	tt.Frame()
	if node, ok := tt.Access("提交全部 1 个文件"); !ok || !node.Disabled {
		t.Fatalf("同步中提交按钮应禁用：%+v, ok=%v", node, ok)
	}
	if err := tt.Click("提交全部 1 个文件"); err != nil {
		t.Fatal(err)
	}
	tt.Key(ui.Cmd, ui.KeyEnter)
	tt.Frame()
	if err := tt.Click("提交选项"); err != nil {
		t.Fatal(err)
	}
	tt.Frame()
	if node, ok := tt.Access("提交并推送"); !ok || !node.Disabled {
		t.Fatalf("同步中提交并推送按钮应禁用：%+v, ok=%v", node, ok)
	}
	if err := tt.Click("提交并推送"); err != nil {
		t.Fatal(err)
	}
	tt.Frame()

	base.paneMu.Lock()
	calls := slices.Clone(base.calls)
	base.paneMu.Unlock()
	if slices.Contains(calls, "commit") {
		t.Fatalf("同步进行中不应调用提交客户端：%v", calls)
	}
}

func TestUIReview12PRApproveAndMergeToasts(t *testing.T) {
	pr := git.PRDetail{PRSummary: git.PRSummary{Number: 42, State: "open"}}
	f := &gitPRDialogFake{FakeClient: NewFakeClient(), prs: []git.PRSummary{pr.PRSummary}, detail: pr}
	s := newGitPRDialogTestState(t, f)
	st := getGitPRDialogState(s)
	st.mu.Lock()
	st.open, st.threadID, st.selected = true, "thread-1", 42
	st.detail = &pr
	st.mu.Unlock()

	s.runGitPRAction("approve", "")
	waitGitPRDialog(t, s, func(st *gitPRDialogState) bool {
		return st.actionBusy == "" && !st.detailLoading && !st.listLoading
	})
	s.mu.Lock()
	approveToast := s.toastMessage
	s.toastMessage = ""
	s.mu.Unlock()
	if approveToast != "已批准" {
		t.Fatalf("PR 批准后 toast = %q，期望 %q", approveToast, "已批准")
	}

	s.runGitPRAction("merge", "squash")
	waitGitPRDialog(t, s, func(st *gitPRDialogState) bool {
		return st.actionBusy == "" && !st.detailLoading && !st.listLoading
	})
	deadline := time.Now().Add(3 * time.Second)
	for {
		s.mu.Lock()
		mergeToast := s.toastMessage
		s.mu.Unlock()
		if mergeToast == "已合并" {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("PR 合并后 toast = %q，期望 %q", mergeToast, "已合并")
		}
		time.Sleep(time.Millisecond)
	}
}
